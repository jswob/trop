//! P8-M4, one point read of a written projection in E §4.3's common case: its instruction
//! count on Linux CI (D4-2, BUILDER §13.3).
//! Spec: P §8.4 (P8-M4), §8.1 (P8-5), §2.3 (the common case); L §5.14.1; E §4.3.
//! Twin: none, an instrument (R-91); its wall time is `engine/crates/tally/benches/p8_m4.rs`,
//! on the same reality.
//! Invariants: the hard limit comes from `engine/tools/perf limits p8_m4`, never from this
//! file; the files and the request are built before the count starts, and the teardown,
//! outside the count, checks the printed value against opening + n × amount, so a fast wrong
//! answer fails the run.
//!
//! One place lives 33 years (12 054 days) with one plan movement a day; `projection` asks
//! `bal(x, E) from S`, `plain` asks `bal(x, E)` of the same reality, so the read itself is the
//! difference of the two counts. A limit set from `projection` holds `plain` too.

use std::hint::black_box;

use gungraun::prelude::*;
use tally::{Answer, Asks, Days, Given, NotImplemented, Pin, Request, run};

/// The run's first day, S, and the projection's day t.
const START: &str = "2025-01-01";
/// The run's last day, E: S + 12 053 days.
const END: &str = "2058-01-01";
/// The days S..E, one plan movement each.
const DAYS: i64 = 12_054;
/// The daily amount, in minor units (1.25 DUK).
const AMOUNT: i64 = 125;
/// The place's opening balance, in minor units (100.00 DUK).
const OPENING: i64 = 10_000;

/// The reality, written in tally 2.1.1 as the corpus writes it, with the two asks.
fn reality() -> String {
    format!(
        "model p8m4\n  tally 2\n  on {START}\n  start {START}\n  end {END}\n\n\
         source card \"P8-M4's reality, generated by its bench\"\n\n\
         unit DUK: currency minor 0.01\n\n\
         kind ext: place DUK signed outside\n\n\
         place out: ext lives {START}..\n\n\
         place x: accounts DUK lives {START}..\n\n\
         input amt: money DUK\n\n\
         move pay[d in days]: transfers\n  on d\n  leg cash from out to x amount amt\n\n\
         version facts\n  cite card\n  governs always\n  known {START}\n  amt = 1.25\n  \
         opening[x] = 100.00 at {START} start\n\n\
         ask plain: bal(x, {END})\n\n\
         ask proj: bal(x, {END}) from {START}\n"
    )
}

/// The run's one file and a request for the one ask named.
fn setup(ask: &str) -> (Vec<Given>, Request) {
    let files = vec![Given {
        path: "p8m4.tally".to_owned(),
        bytes: Some(reality().into_bytes()),
    }];
    let asked = Request {
        asks: Asks::Named(vec![ask.to_owned()]),
        pin: Pin::Canonical,
        days: Days::Events,
    };
    (files, asked)
}

/// Minor units as the engine prints money: whole units grouped by threes with a space, two
/// decimals (`15 167.50`). None on overflow.
fn money_text(minor: i64) -> Option<String> {
    let whole = minor.checked_div_euclid(100)?;
    let cents = minor.checked_rem_euclid(100)?;
    let digits = whole.to_string();
    let mut grouped = String::new();
    for (i, digit) in digits.chars().enumerate() {
        let left = digits.len().checked_sub(i)?;
        if i > 0 && left.checked_rem_euclid(3)? == 0 {
            grouped.push(' ');
        }
        grouped.push(digit);
    }
    Some(format!("{grouped}.{cents:02}"))
}

/// Whether the answer printed is opening + n × amount at the cut S, for the ask it names.
fn known(asked: &Request, answer: &Result<Answer, NotImplemented>) -> Option<bool> {
    let Asks::Named(names) = &asked.asks else {
        return Some(false);
    };
    let ask = names.first()?;
    let balance = DAYS.checked_mul(AMOUNT)?.checked_add(OPENING)?;
    let lines = [
        format!("{ask}: {} DUK", money_text(balance)?),
        format!("  cut {START}"),
    ];
    Some(answer.as_ref().is_ok_and(|a| a.lines() == lines.as_slice()))
}

fn check(result: (Request, Result<Answer, NotImplemented>)) {
    let (asked, answer) = result;
    assert_eq!(
        known(&asked, &answer),
        Some(true),
        "P8-M4: a fast wrong answer fails"
    );
}

#[library_benchmark(teardown = check)]
#[bench::projection(setup("proj"))]
#[bench::plain(setup("plain"))]
fn p8_m4(input: (Vec<Given>, Request)) -> (Request, Result<Answer, NotImplemented>) {
    let (files, asked) = black_box(input);
    let answer = run(files, &asked);
    (asked, answer)
}

library_benchmark_group!(name = micro, benchmarks = p8_m4);

main!(library_benchmark_groups = micro);
