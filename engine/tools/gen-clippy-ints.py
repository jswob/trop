"""Generate the per-integer entries of engine/clippy.toml's disallowed-methods (R-7, R-44).

    python3 -I tools/gen-clippy-ints.py --write   # rewrite the block in clippy.toml
    python3 -I tools/gen-clippy-ints.py --check   # fail if the block is out of date

The block sits between the BEGIN and END marker lines. Every path must resolve on the
pinned toolchain: rules-selftest fails on clippy's "does not refer to a reachable" note.
"""

import pathlib
import sys

CLIPPY_TOML = pathlib.Path(__file__).resolve().parent.parent / "clippy.toml"
BEGIN = "  # --- BEGIN generated by tools/gen-clippy-ints.py: per-integer entries ---"
END = "  # --- END generated ---"

SIGNED = ["i8", "i16", "i32", "i64", "i128", "isize"]
UNSIGNED = ["u8", "u16", "u32", "u64", "u128", "usize"]

# (method, reason, replacement or None); {t} is the integer type
ALL = [
    ("pow", "R-7: panics on overflow", "checked_pow"),
    ("ilog", "R-7: panics on a non-positive value or base", "checked_ilog"),
    ("ilog2", "R-7: panics on a non-positive value", "checked_ilog2"),
    ("ilog10", "R-7: panics on a non-positive value", "checked_ilog10"),
    ("div_euclid", "R-7: panics on a zero divisor", "checked_div_euclid"),
    ("rem_euclid", "R-7: panics on a zero divisor", "checked_rem_euclid"),
    ("strict_add", "R-7: panics on overflow by design", "checked_add"),
    ("strict_sub", "R-7: panics on overflow by design", "checked_sub"),
    ("strict_mul", "R-7: panics on overflow by design", "checked_mul"),
    ("strict_div", "R-7: panics by design", "checked_div"),
    ("strict_rem", "R-7: panics by design", "checked_rem"),
    ("strict_pow", "R-7: panics on overflow by design", "checked_pow"),
    ("strict_neg", "R-7: panics by design", "checked_neg"),
    ("strict_shl", "R-7: panics by design", "checked_shl"),
    ("strict_shr", "R-7: panics by design", "checked_shr"),
    ("strict_div_euclid", "R-7: panics by design", "checked_div_euclid"),
    ("strict_rem_euclid", "R-7: panics by design", "checked_rem_euclid"),
    ("to_ne_bytes", "R-44: depends on the CPU's byte order", "to_le_bytes"),
    ("from_ne_bytes", "R-44: depends on the CPU's byte order", "from_le_bytes"),
]
SIGNED_ONLY = [
    ("abs", "R-7: panics on MIN", "checked_abs"),
    ("isqrt", "R-7: panics on a negative value", "checked_isqrt"),
    ("strict_abs", "R-7: panics by design", "checked_abs"),
]
UNSIGNED_ONLY = [
    ("next_power_of_two", "R-7: overflows past the largest power", "checked_next_power_of_two"),
    ("div_ceil", "R-7: panics on a zero divisor", None),
    ("next_multiple_of", "R-7: panics on zero and on overflow", "checked_next_multiple_of"),
]
WORD_SIZE = [
    ("to_le_bytes", "R-44: the width depends on the machine's word size"),
    ("to_be_bytes", "R-44: the width depends on the machine's word size"),
    ("from_le_bytes", "R-44: the width depends on the machine's word size"),
    ("from_be_bytes", "R-44: the width depends on the machine's word size"),
]


def entries() -> list[str]:
    lines = []
    for t in SIGNED + UNSIGNED:
        table = ALL + (SIGNED_ONLY if t in SIGNED else UNSIGNED_ONLY)
        for method, reason, replacement in table:
            if t in ("usize", "isize") and method in ("to_ne_bytes", "from_ne_bytes"):
                reason = "R-44: depends on the CPU's byte order and word size"
                replacement = None
            line = f'  {{ path = "{t}::{method}", reason = "{reason}"'
            if replacement is not None:
                line += f', replacement = "{t}::{replacement}"'
            lines.append(line + " },")
        if t in ("usize", "isize"):
            for method, reason in WORD_SIZE:
                lines.append(f'  {{ path = "{t}::{method}", reason = "{reason}" }},')
    return lines


def render(text: str) -> str:
    before, sep, rest = text.partition(BEGIN + "\n")
    if not sep:
        sys.exit(f"gen-clippy-ints: no BEGIN marker in {CLIPPY_TOML}")
    _, sep, after = rest.partition(END + "\n")
    if not sep:
        sys.exit(f"gen-clippy-ints: no END marker in {CLIPPY_TOML}")
    return before + BEGIN + "\n" + "\n".join(entries()) + "\n" + END + "\n" + after


def main() -> None:
    mode = sys.argv[1] if len(sys.argv) == 2 else ""
    text = CLIPPY_TOML.read_text(encoding="utf-8")
    new = render(text)
    if mode == "--write":
        CLIPPY_TOML.write_text(new, encoding="utf-8")
    elif mode == "--check":
        if new != text:
            sys.exit("gen-clippy-ints: the per-integer block in clippy.toml is out of date (R-7)")
    else:
        sys.exit("usage: gen-clippy-ints.py --write|--check")


if __name__ == "__main__":
    main()
