"""The kernel's property generator (T1, issue #5; PROPERTIES.md). Standard library only.

Writes kernel.corpus: small random realities in household X's base forms (accounts and signed outside places,
openings, transfers with stated amounts and days, a decision with declared reads that sweeps a balance over a stated
floor, a later version, `as known` asks), each in the variants its law compares. Seeded, so the corpus is the same
bytes on every run; `--check` fails when the file on disk differs from what the seeds give.

    python3 -I -B engine/tests/properties/gen.py            -> writes kernel.corpus
    python3 -I -B engine/tests/properties/gen.py --check    -> exit 1 if kernel.corpus isn't what the seeds give

The corpus is a sequence of records, each five netstrings (`<len>:<bytes>,`): the law, the case id, the variant, the
argument words joined by single spaces, and the file table (INTERFACE.md §4: netstring pairs, path then content).
The runner embeds it (engine/tests/runner/src/corpus.rs, include_bytes!) for milestone/s_properties.rs; laws.py runs it
on refcore.

Every figure is a stated input (Tally explicit: a literal date or figure in a rule is refused, LOAD-LITERAL). The only
literals in expressions are 0 (max(0, …)) and the ask's own zeros in the hole law.
"""
import datetime as dt
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS = os.path.join(HERE, 'kernel.corpus')
SEED = 20261031
CASES = 24  # per law
START = dt.date(2025, 1, 1)
END = dt.date(2025, 3, 31)


def ns(b):
    b = b if isinstance(b, bytes) else b.encode('utf-8')
    return b'%d:' % len(b) + b + b','


def table(files):
    return b''.join(ns(p) + ns(t) for p, t in files)


def day(r, lo=START, hi=END):
    return lo + dt.timedelta(days=r.randrange((hi - lo).days + 1))


def money(r, lo=1, hi=200000):
    c = r.randrange(lo, hi + 1)
    return '%d.%02d' % (c // 100, c % 100)


class Reality:
    """One random reality: its sections as (kind, text) so a variant can split and reorder them."""

    def __init__(self, r, name, decision=False):
        self.r = r
        self.name = name
        self.layout = None  # the order of rows and files: its own seed, so variants differ only in what they change
        self.on = day(r, dt.date(2025, 2, 1), END)
        self.acc = ['acc_%d' % i for i in range(r.randint(2 if decision else 1, 4))]
        self.out = ['out_%d' % i for i in range(r.randint(1, 2))]
        places = self.acc + self.out
        self.moves = []
        for k in range(r.randint(1, 6)):
            a, b = r.sample(places, 2)
            self.moves.append(dict(id='mv_%d' % k, src=a, dst=b, amt=money(r), day=day(r)))
        self.openings = {a: money(r, 0, 500000) for a in self.acc}
        self.sweep = None
        if decision:
            a, b = r.sample(self.acc, 2)
            self.sweep = dict(src=a, dst=b, floor=money(r, 0, 300000), day=day(r, dt.date(2025, 1, 15), dt.date(2025, 3, 15)))
        self.extra_rows = []      # rows of version `facts` a variant adds (a later move's amount and day)
        self.extra_moves = []     # moves a variant adds
        self.late = None          # (known day, row) of a later version
        self.drop = None          # an input whose row a variant leaves out
        self.asks = []            # (name, expression)

    def span(self):
        return '%s .. %s' % (START, END)

    def sections(self):
        s = [('model', 'model %s\n  tally 2\n  on %s\n  start %s\n  end %s\n' % (self.name, self.on, START, END)),
             ('', 'source card "generated by engine/tests/properties/gen.py"\n'),
             ('', 'unit DUK: currency minor 0.01\n'),
             ('', 'kind ext: place DUK signed outside\n')]
        s += [('', 'place %s: ext lives %s..\n' % (p, START)) for p in self.out]
        s += [('', 'place %s: accounts DUK lives %s..\n' % (p, START)) for p in self.acc]
        rows = []
        for m in self.moves + self.extra_moves:
            q = ' question "How much does %s move?"' % m['id']
            s.append(('', 'input amt_%s: money DUK%s\n' % (m['id'], q)))
            s.append(('', 'input day_%s: date question "On what day does %s move?"\n' % (m['id'], m['id'])))
            s.append(('', 'move %s: transfers\n  on day_%s\n  leg cash from %s to %s amount amt_%s\n'
                      % (m['id'], m['id'], m['src'], m['dst'], m['id'])))
            rows += ['amt_%s = %s' % (m['id'], m['amt']), 'day_%s = %s' % (m['id'], m['day'])]
        if self.sweep:
            w = self.sweep
            s.append(('', 'input sweep_floor: money DUK\n'))
            s.append(('', 'input sweep_day: date\n'))
            read = 'bal(%s)' % w['src']
            if w.get('reach'):  # the written projection (L §5.14.1): the lowest balance it sees through its reach
                s.append(('', 'input sweep_reach: date\n'))
                s.append(('', 'def low_room: money DUK at sweep_day\n  rule base = min(bal(%s, d) from sweep_day for d in '
                          'sweep_day .. sweep_reach step 1 day)\n' % w['src']))
                rows.append('sweep_reach = %s' % w['reach'])
                read = 'low_room'
            s.append(('', 'move sweep: transfers\n  on sweep_day\n  reads %s\n  leg cash from %s to %s amount '
                      'max(0, %s - sweep_floor)\n' % (w['src'], w['src'], w['dst'], read)))
            rows += ['sweep_floor = %s' % w['floor'], 'sweep_day = %s' % w['day']]
        rows += ['opening[%s] = %s at %s start' % (a, v, START) for a, v in sorted(self.openings.items())]
        rows = [x for x in rows if not (self.drop and x.startswith(self.drop + ' = '))]
        self.layout.shuffle(rows)
        s.append(('', 'version facts\n  cite card\n  governs always\n  known %s\n' % START + ''.join('  %s\n' % x for x in rows)))
        if self.late:
            s.append(('', 'version late\n  cite card\n  governs always\n  known %s\n  replace %s\n' % self.late))
        s += [('', 'ask %s: %s\n' % a) for a in self.asks]
        return s

    def files(self, split=False):
        """One file, or (split) the sections spread over 2-3 files in shuffled order, the model header's file first in
        no particular place; the returned order is the order of the command line."""
        self.layout = random.Random(self.name)
        secs = self.sections()
        if not split:
            return [('reality.tally', '\n'.join(t for _, t in secs))]
        r = self.layout
        n = r.randint(2, 3)
        head = secs[0]
        rest = secs[1:]
        r.shuffle(rest)
        bins = [[] for _ in range(n)]
        for x in rest:
            bins[r.randrange(n)].append(x)
        names = ['model.tally'] + ['part_%d.tally' % i for i in range(1, n)]
        out = []
        for i, b in enumerate(bins):
            if i == 0:
                body = [head[1]] + [t for _, t in b]
            else:
                body = ['part p%d\n  tally 2\n' % i] + [t for _, t in b]
            out.append((names[i], '\n'.join(body)))
        r.shuffle(out)
        return out


def record(law, case, variant, files):
    args = 'run ' + ' '.join(p for p, _ in files)
    return ns(law) + ns(case) + ns(variant) + ns(args) + ns(table(files))


def all_flows(x):
    return ', '.join('flows(%s, %s)' % (p, x.span()) for p in x.out + x.acc)


def determinism(r, i):
    """A reality as one file, and as the same sections spread over 2-3 files in another order (L §9 l.1784: the
    order of files and of sections changes nothing; R-47)."""
    x = Reality(r, 'det%02d' % i, decision=r.random() < 0.5)
    x.asks = [('flows_all', all_flows(x)), ('bals', ', '.join('bal(%s, %s)' % (a, END) for a in x.acc))]
    if x.sweep:
        x.asks.append(('swept', 'flows(sweep, %s)' % x.span()))
    return [('one', x.files()), ('split', x.files(split=True))]


def conservation(r, i):
    """Every place's flows over the run, outside places included: the two ends of each leg sum to zero (E §9.1)."""
    x = Reality(r, 'con%02d' % i, decision=r.random() < 0.5)
    x.asks = [('flows_all', all_flows(x))]
    return [('one', x.files())]


def foresight_known(r, i):
    """A later version, known after the ask's `as known D`, changes nothing the ask prints (L §4.5 the ask's cut K;
    DONE gate 6: a cut never reads a version known after it). `at_on` lines are the control: they see it."""
    x = Reality(r, 'fk%02d' % i, decision=r.random() < 0.5)
    m = r.choice(x.moves)
    known_late = day(r, dt.date(2025, 1, 10), x.on)
    as_known = day(r, START, known_late - dt.timedelta(days=1))
    q = all_flows(x) + ', ' + ', '.join('bal(%s, %s)' % (a, END) for a in x.acc)
    x.asks = [('early', '%s as known %s' % (q, as_known)), ('at_on', q)]
    base = x.files()
    new = money(r)
    while new == m['amt']:
        new = money(r)
    x.late = (known_late, 'amt_%s = %s' % (m['id'], new))
    return [('base', base), ('later', x.files())]


def foresight_decision(r, i):
    """A movement dated after a decision's day changes nothing the decision moved (D-5: a decision reads the walk as it
    stands on its day; L §5.14.1). The control adds the same movement on a day before the decision's."""
    x = Reality(r, 'fd%02d' % i, decision=True)
    w = x.sweep
    # the floor under the decision's place's opening, so a movement into it before the decision changes the sweep
    w['floor'] = money(r, 0, max(1, int(float(x.openings[w['src']]) * 100) // 2))
    x.asks = [('swept', 'flows(sweep, %s)' % x.span())]
    base = x.files()
    amt = money(r, 100, 100000)
    after = day(r, w['day'] + dt.timedelta(days=1), END)
    before = day(r, START, w['day'] - dt.timedelta(days=1))
    x.extra_moves = [dict(id='mv_x', src=r.choice(x.out), dst=w['src'], amt=amt, day=after)]
    later = x.files()
    x.extra_moves = [dict(id='mv_x', src=x.extra_moves[0]['src'], dst=w['src'], amt=amt, day=before)]
    return [('base', base), ('later', later), ('control', x.files())]


def hole(r, i):
    """An input's row left out: every value that reads it prints a hole with the input's question, never a number;
    `* 0`, `- itself` and `+ 0` stay holes (L §8.1: a hole is never 0; it stops propagating only where the outcome is
    decided without it, and arithmetic isn't such a place)."""
    x = Reality(r, 'ho%02d' % i, decision=r.random() < 0.5)
    m = r.choice(x.moves)
    a = 'amt_%s' % m['id']
    x.asks = [('flows_all', all_flows(x)), ('bals', ', '.join('bal(%s, %s)' % (p, END) for p in x.acc)),
              ('zero', '%s * 0, %s - %s, %s + 0' % (a, a, a, a))]
    base = x.files()
    x.drop = a
    return [('base', base), ('dropped', x.files())]


def foresight_projection(r, i):
    """A decision that reads the written projection `bal(x, d) from t` through its reach: a movement dated after the
    reach changes nothing it moved; the control, the same movement out of x inside the reach, lowers what it sees
    (L §5.14.1; DONE gate 6: no row after the written projection's reach changes a decision before it; D-6)."""
    x = Reality(r, 'fp%02d' % i, decision=True)
    w = x.sweep
    w['day'] = day(r, dt.date(2025, 1, 15), dt.date(2025, 2, 28))
    w['reach'] = day(r, w['day'] + dt.timedelta(days=7), dt.date(2025, 3, 20))
    # sizes, not answers: the place opens far above everything the other moves can take (6 x 2 000.00) plus the floor
    # and the extra outflow, so the sweep moves money in every variant, and an outflow the day after the decision lowers
    # every projected day but the first below the first: the control can't be vacuous
    x.openings[w['src']] = money(r, 10000000, 12000000)
    w['floor'] = money(r, 0, 5000000)
    x.asks = [('swept', 'flows(sweep, %s)' % x.span())]
    base = x.files()
    amt = money(r, 3000000, 3500000)
    out = r.choice(x.out)
    x.extra_moves = [dict(id='mv_x', src=w['src'], dst=out, amt=amt, day=day(r, w['reach'] + dt.timedelta(days=1), END))]
    beyond = x.files()
    x.extra_moves = [dict(id='mv_x', src=w['src'], dst=out, amt=amt, day=w['day'] + dt.timedelta(days=1))]
    return [('base', base), ('later', beyond), ('control', x.files())]


LAWS = [('determinism', determinism), ('conservation', conservation), ('foresight-known', foresight_known),
        ('foresight-decision', foresight_decision), ('foresight-projection', foresight_projection), ('hole', hole)]


def corpus():
    out = []
    for law, f in LAWS:
        r = random.Random('%d/%s' % (SEED, law))
        for i in range(CASES):
            for variant, files in f(r, i):
                out.append(record(law, '%s-%02d' % (law, i), variant, files))
    return b''.join(out)


def records(b):
    """The corpus back as (law, case, variant, args, [(path, text)])."""
    def take(b, i):
        j = b.index(b':', i)
        n = int(b[i:j])
        assert b[j + 1 + n:j + 2 + n] == b',', 'netstring at %d' % i
        return b[j + 1:j + 1 + n], j + 2 + n
    i, out = 0, []
    while i < len(b):
        f = []
        for _ in range(5):
            v, i = take(b, i)
            f.append(v)
        t, k, files = f[4], 0, []
        while k < len(t):
            p, k = take(t, k)
            c, k = take(t, k)
            files.append((p.decode(), c.decode()))
        out.append((f[0].decode(), f[1].decode(), f[2].decode(), f[3].decode(), files))
    return out


def main(argv):
    b = corpus()
    if '--check' in argv:
        same = os.path.exists(CORPUS) and open(CORPUS, 'rb').read() == b
        print('kernel.corpus %s the seeds (%d records)' % ('matches' if same else 'DIFFERS from', len(records(b))))
        return 0 if same else 1
    with open(CORPUS, 'wb') as f:
        f.write(b)
    print('wrote kernel.corpus: %d records, %d bytes' % (len(records(b)), len(b)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
