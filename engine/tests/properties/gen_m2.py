"""M2's property generator (T, issue #167; PROPERTIES.md § M2). Standard library only.

Writes m2.corpus, in kernel.corpus's form (gen.py's netstrings: law, case, variant, argument words, file table): small
random realities in M2's forms, each in the variants its law compares. A reality is a household month by month: a
joint account `konto` covered by monthly statements (`covers konto`, `pad konto from unexplained`, each row linked to
the instance it fulfils, `stated[konto]` at the month's end), a savings account, pay from a flat tax law that reads
the month's payslip where one is known (a cited `missing()` rule, L §5.11) and the contract's gross otherwise, rent
and a monthly saving. Every figure is a stated row (Tally explicit).

The laws (PROPERTIES.md § M2):
- `masking`: an ask `as known K` prints the same bytes with and without one row known after K, of a random kind: an
  observed row in a statement known after K, a version changing a plan's amount, a payslip (E §2; hindcast H8's
  law). Control: the same reads at `on` see the row.
- `split`: in the replay (`residuals` at K = `on`, the law reading the payslips), every matched line of pay, a
  law-computed instance, has amount difference 0.00 (E §6.2, §6.3; hindcast.md §4's three-way split). Control: the
  twin whose law rounds down where the statements' law rounds half-up.
- `fixed-past`: a plan's booked amount never changes; a version known on D changing it leaves every balance and flow
  before D as without it (L §5.14.3, E §5). Control: the same version known before the first booking changes them.

    python3 -I -B engine/tests/properties/gen_m2.py            -> writes m2.corpus
    python3 -I -B engine/tests/properties/gen_m2.py --check    -> exit 1 if m2.corpus isn't what the seeds give
"""
import datetime as dt
import os
import random
import sys
from decimal import ROUND_DOWN, ROUND_HALF_UP, Decimal as Dec

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import properties.gen as G  # noqa: E402

CORPUS = os.path.join(HERE, 'm2.corpus')
SEED = 20261115
CASES = 24  # per law
START = dt.date(2025, 1, 1)
END = dt.date(2025, 6, 30)
RATES = ['0.12', '0.17', '0.19', '0.23']


def month_of(i):
    return '2025-%02d' % (i + 1)


def mday(i, dom):
    return dt.date(2025, i + 1, dom)


def month_end(i):
    return (dt.date(2025, i + 2, 1) if i < 11 else dt.date(2026, 1, 1)) - dt.timedelta(days=1)


def cents(r, lo, hi):
    return Dec(r.randrange(lo, hi + 1)) / 100


def d2(x):
    return '%.2f DUK' % x


class H:
    """One random household: its constants, and the text of its model and its statements."""

    def __init__(self, r, name, on, months_covered, slips_to):
        self.r, self.name, self.on = r, name, on
        self.covered, self.slips_to = months_covered, slips_to
        self.rate = Dec(r.choice(RATES))
        self.contract = cents(r, 300000, 900000)
        self.gross = [cents(r, 300000, 900000) for _ in range(6)]
        self.pay_dom = r.randint(5, 12)
        self.rent, self.rent_dom = cents(r, 50000, 200000), r.randint(1, 4)
        self.save, self.save_dom = cents(r, 10000, 90000), r.randint(14, 20)
        self.opening = cents(r, 100000, 900000)
        self.extra = {i: (r.randint(21, 27), cents(r, 100, 90000)) for i in range(6) if r.random() < 0.3}
        self.asks = []

    def tax(self, gross, mode=ROUND_HALF_UP):
        return (gross * self.rate).quantize(Dec('1'), rounding=mode)

    def net(self, i):
        return self.gross[i] - self.tax(self.gross[i])

    def model(self):
        t = ['model %s' % self.name, '  tally 2', '  on %s' % self.on, '  start %s' % START, '  end %s' % END, '',
             'index month = month 2025-01..2025-06', '',
             'source card "generated by engine/tests/properties/gen_m2.py"', 'unit DUK: currency minor 0.01', '',
             'kind wages: event certain', '  leg cash: DUK', '',
             'input bank: observed', 'input contract: money DUK', 'input slip[m in month]: money DUK',
             'input tax_rate: num', 'input law_truncates: bool', 'input pay_dom: int', 'input rent_amt: money DUK',
             'input rent_dom: int', 'input save_amt: money DUK', 'input save_dom: int', '',
             'place konto: accounts DUK lives 2024-01-01..', 'place sav: accounts DUK lives 2024-01-01..',
             'place employer: outside lives 1900-01-01..', 'place landlord: outside lives 1900-01-01..',
             'place shops: outside lives 1900-01-01..', 'place unexplained: outside lives 1900-01-01..', '',
             'def gross[m in month]: money DUK at start_of(m)', '  rule contract = contract',
             '  rule slip beats contract v plan = slip[m] when not missing(slip[m])',
             'def tax[m in month]: money DUK at start_of(m)',
             '  rule half_up = round(gross[m] * tax_rate, 1, half-up)',
             '  rule truncated beats half_up = round(gross[m] * tax_rate, 1, down) when law_truncates',
             'def net[m in month]: money DUK = gross[m] - tax[m] at start_of(m)', '',
             'move pay[m in month]: wages', '  on day_of(m, pay_dom)', '  at start_of(m)',
             '  leg cash from employer to konto amount net[m]',
             'move rent[m in month]: transfers', '  on day_of(m, rent_dom)', '  at start_of(m)',
             '  leg cash from konto to landlord amount rent_amt',
             'move save[m in month]: transfers', '  on day_of(m, save_dom)', '  at start_of(m)',
             '  leg cash from konto to sav amount save_amt', '',
             'version plan', '  cite card', '  governs always', '  known 2024-12-30',
             '  contract = %s "umowa"' % d2(self.contract), '  tax_rate = %s "ustawa"' % self.rate,
             '  law_truncates = false "ustawa"', '  pay_dom = %d "umowa"' % self.pay_dom,
             '  rent_amt = %s "umowa najmu"' % d2(self.rent), '  rent_dom = %d "umowa najmu"' % self.rent_dom,
             '  save_amt = %s "zlecenie"' % d2(self.save), '  save_dom = %d "zlecenie"' % self.save_dom,
             '  opening[konto] = %s at 2025-01-01 start "wyciąg"' % d2(self.opening),
             '  opening[sav] = 0.00 DUK at 2025-01-01 start "wyciąg"', '']
        for i in range(self.slips_to):
            t += ['version slip_%d' % (i + 1), '  cite card', '  governs %s' % month_of(i),
                  '  known %s' % mday(i, self.pay_dom), '  slip[%s] = %s "pasek"' % (month_of(i), d2(self.gross[i])),
                  '']
        balance = self.opening
        for i in range(self.covered):
            rows, balance = self.statement(i, balance)
            t += rows + ['']
        t += ['ask %s: %s' % (n, e) for n, e in self.asks]
        return '\n'.join(t) + '\n'

    def rows(self, i):
        out = [(self.rent_dom, 'konto', 'landlord', self.rent, 'rent[%s]' % month_of(i)),
               (self.pay_dom, 'employer', 'konto', self.net(i), 'pay[%s]' % month_of(i)),
               (self.save_dom, 'konto', 'sav', self.save, 'save[%s]' % month_of(i))]
        if i in self.extra:
            out.append((self.extra[i][0], 'konto', 'shops', self.extra[i][1], None))
        return sorted(out, key=lambda x: (x[0], x[4] or '~'))

    def statement(self, i, balance, extra=None):
        t = ['version st_%d' % (i + 1), '  cite card', '  governs %s' % month_of(i),
             '  known %s' % (month_end(i) + dt.timedelta(days=2)), '  covers konto', '  pad konto from unexplained']
        rows = self.rows(i) + ([extra] if extra else [])
        for k, (dom, a, b, amount, link) in enumerate(sorted(rows, key=lambda x: (x[0], x[4] or '~'))):
            kind = 'wages' if (link or '').startswith('pay[') else 'transfers'
            t.append('  bank[r%d_%d] = (on: %s, kind: %s, leg cash from %s to %s amount %s%s) "line %d"' % (
                i + 1, k, mday(i, dom), kind, a, b, d2(amount), ', fulfils: %s' % link if link else '', k))
            balance += amount if b == 'konto' else -amount
        t.append('  stated[konto] = %s at %s end "saldo"' % (d2(balance), month_end(i)))
        return t, balance


def part(name, lines):
    return '\n'.join(['part %s' % name, '  tally 2', ''] + lines) + '\n'


# -- the laws' generators: each returns [(variant, files)] ----------------------------------------------------------

def masking(r, i):
    """One row known after K: an observed row in the first statement known after K, a version changing rent's
    amount, or a payslip; every ask `as known K` prints what it prints without it (E §2)."""
    on = dt.date(2025, 4, 20)
    x = H(r, 'mask%02d' % i, on, 3, 4)
    k = G.day(r, dt.date(2025, 2, 3), dt.date(2025, 3, 30))
    late = G.day(r, k + dt.timedelta(days=1), on)
    days = sorted({G.day(r, START, k), G.day(r, k, END), END})
    x.asks = [('k_bal_%d' % j, 'bal(konto, %s) as known %s' % (d, k)) for j, d in enumerate(days)]
    x.asks += [('k_sav', 'bal(sav, %s) as known %s' % (END, k)), ('k_net', 'net[2025-05] as known %s' % k),
               ('k_flows', 'flows(konto, %s .. %s) as known %s' % (START, END, k)),
               ('o_bal', 'bal(konto, %s)' % END), ('o_net', 'net[2025-05]'),
               ('o_flows', 'flows(konto, %s .. %s)' % (START, END))]
    kind = r.choice(['obs', 'plan', 'slip'])
    base = x.model()
    if kind == 'obs':
        # the March statement, known 2025-04-02 > K, with one more row
        balance = x.opening + sum((a if b == 'konto' else -a) for j in range(2) for (_, _, b, a, _) in x.rows(j))
        st, _ = x.statement(2, balance, (r.randint(21, 28), 'konto', 'shops', cents(r, 100, 90000), None))
        old, _ = x.statement(2, balance)
        late_text = base.replace('\n'.join(old), '\n'.join(st))
        assert late_text != base
        return [('base', [('m.tally', base)]), ('late', [('m.tally', late_text)])]
    if kind == 'plan':
        lines = ['version late', '  cite card', '  governs 2025-01..', '  known %s' % late,
                 '  replace rent_amt = %s "aneks"' % d2(x.rent + cents(r, 100, 50000))]
    else:
        lines = ['version late', '  cite card', '  governs 2025-05', '  known %s' % late,
                 '  slip[2025-05] = %s "pasek"' % d2(x.contract + cents(r, 100, 90000))]
    return [('base', [('m.tally', base)]), ('late', [('m.tally', base), ('late.tally', part('late_%s' % kind, lines))])]


def split(r, i):
    """The replay: every matched pay line, a law-computed instance, has difference 0.00; the twin whose law rounds
    down shows a difference (E §6.2, §6.3; hindcast.md §4)."""
    while True:
        x = H(r, 'split%02d' % i, dt.date(2025, 7, 10), 6, 6)
        if any(x.tax(g) != x.tax(g, ROUND_DOWN) for g in x.gross):
            break
    x.asks = [('rep', 'residuals konto 2025-01..2025-06')]
    base = x.model()
    bug = part('law_bug', ['version law_bug', '  cite card', '  governs always', '  known 2024-12-31',
                           '  replace law_truncates = true "the modeller\'s reading"'])
    return [('model', [('m.tally', base)]), ('bug', [('m.tally', base), ('bug.tally', bug)])]


def fixed_past(r, i):
    """A version known on D changing rent's amount leaves every balance and flow before D as without it (L §5.14.3);
    known before the first booking, it changes them."""
    x = H(r, 'past%02d' % i, dt.date(2025, 6, 20), 0, 0)
    d = G.day(r, dt.date(2025, 2, 10), dt.date(2025, 5, 25))
    first = mday(0, x.rent_dom)
    days = sorted({G.day(r, first, d - dt.timedelta(days=1)), G.day(r, START, d - dt.timedelta(days=1)),
                   d - dt.timedelta(days=1)})
    x.asks = [('b_%d' % j, 'bal(konto, %s)' % day_) for j, day_ in enumerate(days)]
    x.asks += [('f_pre', 'flows(konto, %s .. %s)' % (START, d - dt.timedelta(days=1)))]
    base = x.model()
    new = d2(x.rent + cents(r, 100, 50000))

    def v(known):
        return part('raise', ['version raise', '  cite card', '  governs 2025-01..', '  known %s' % known,
                              '  replace rent_amt = %s "aneks"' % new])
    return [('base', [('m.tally', base)]), ('late', [('m.tally', base), ('raise.tally', v(d))]),
            ('early', [('m.tally', base), ('raise.tally', v(dt.date(2024, 12, 31)))])]


LAWS = [('masking', masking), ('split', split), ('fixed-past', fixed_past)]


def corpus():
    out = []
    for law, f in LAWS:
        r = random.Random('%d/%s' % (SEED, law))
        for i in range(CASES):
            for variant, files in f(r, i):
                out.append(G.record(law, '%s-%02d' % (law, i), variant, files))
    return b''.join(out)


def main(argv):
    b = corpus()
    if '--check' in argv:
        same = os.path.exists(CORPUS) and open(CORPUS, 'rb').read() == b
        print('m2.corpus %s the seeds (%d records)' % ('matches' if same else 'DIFFERS from', len(G.records(b))))
        return 0 if same else 1
    with open(CORPUS, 'wb') as f:
        f.write(b)
    print('wrote m2.corpus: %d records, %d bytes' % (len(G.records(b)), len(b)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
