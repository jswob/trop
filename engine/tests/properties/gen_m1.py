"""M1's property generator (T, issue #108; PROPERTIES.md § M1). Standard library only.

Writes m1.corpus, in kernel.corpus's form (gen.py's netstrings: law, case, variant, argument words, file table): small
random realities in M1's forms, each in the variants its law compares. On top of the kernel's base (accounts, signed
outside places, openings, one-off transfers with stated amounts and days), a reality may hold a plan over a month index
(`move plan[m in month]`), a prorata split over a list (`prorata(..., rest largest ties by pos(j))`) booked by a keyed
move, a fee def with a rule `when` and a band, a decision with declared reads and its keyed twin (`move ksweep[m in
month]`), a place with a lifespan, and a scenario `from D`. Every figure is a stated row (Tally explicit); the only
literals in expressions are 0 and `0 DUK`.

    python3 -I -B engine/tests/properties/gen_m1.py            -> writes m1.corpus
    python3 -I -B engine/tests/properties/gen_m1.py --check    -> exit 1 if m1.corpus isn't what the seeds give

The steps law (#98's class) carries its own oracle: the generator writes into the model's note what each ask must
print, computed from the index's declaration alone with Python's datetime (keys are start + i * n periods, anchored by
`from`), never from refcore.
"""
import datetime as dt
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import properties.gen as G  # noqa: E402

CORPUS = os.path.join(HERE, 'm1.corpus')
SEED = 20261109
CASES = 24  # per law
START = dt.date(2025, 1, 1)
END = dt.date(2025, 6, 30)
MONTHS = ['2025-%02d' % m for m in range(1, 7)]
SPAN = '%s .. %s' % (START, END)


def day(r, lo=START, hi=END):
    return G.day(r, lo, hi)


def money(r, lo=1, hi=200000):
    return G.money(r, lo, hi)


def plus(d, n):
    return d + dt.timedelta(days=n)


def month_start(m):
    y, mo = m.split('-')
    return dt.date(int(y), int(mo), 1)


class R1:
    """One random reality in M1's forms: its sections as (kind, text), so a variant can split and reorder them."""

    def __init__(self, r, name, plan=True, split=True, fee=True, sweep=False, ksweep=False, inside_sweep=False,
                 n_moves=None):
        self.r = r
        self.name = name
        self.layout = None
        self.on = day(r, dt.date(2025, 2, 1), END)
        self.acc = ['acc_%d' % i for i in range(r.randint(2, 4))]
        self.out = ['out_%d' % i for i in range(r.randint(1, 2))]
        places = self.acc + self.out
        self.moves = []
        for k in range(n_moves if n_moves is not None else r.randint(1, 4)):
            a, b = r.sample(places, 2)
            self.moves.append(dict(id='mv_%d' % k, src=a, dst=b, amt=money(r, 100), day=day(r)))
        self.openings = {a: money(r, 0, 500000) for a in self.acc}
        self.plan = dict(src=r.choice(self.out), dst=r.choice(self.acc), amt=money(r, 100, 100000),
                         off=r.randint(0, 27)) if plan else None
        self.split = dict(src=r.choice(self.acc), dst=r.choice(self.out), amt=money(r, 100, 100000), day=day(r),
                          w=[r.randint(1, 9) for _ in range(3)]) if split else None
        self.fee = dict(src=r.choice(self.acc), dst=r.choice(self.out), base=money(r, 100, 300000),
                        rate=r.choice(['0', '0.01', '0.02', '0.05', '0.1']), day=day(r)) if fee else None
        self.sweep = None
        if sweep:
            a, b = r.sample(self.acc, 2)
            self.sweep = dict(src=a, dst=b if inside_sweep or r.random() < 0.5 else r.choice(self.out),
                              floor=money(r, 0, 300000), day=day(r, dt.date(2025, 1, 15), dt.date(2025, 6, 15)))
        self.ksweep = None
        if ksweep:
            a, b = r.sample(self.acc, 2)
            self.ksweep = dict(src=a, dst=b if inside_sweep or r.random() < 0.5 else r.choice(self.out),
                               floor=money(r, 0, 300000), off=r.randint(0, 27))
        self.life = None          # (place, from, to, in day, out day, amount): a place with a lifespan
        self.extra_moves = []     # one-off moves a variant adds
        self.drop = None          # an input whose row a variant leaves out
        self.asks = []            # (name, expression)
        self.scenario = None      # (from day, [rows it replaces]): a scenario file `s` over the model

    def places(self):
        return self.out + self.acc + ([self.life[0]] if self.life else [])

    def sections(self):
        s = [('model', 'model %s\n  tally 2\n  on %s\n  start %s\n  end %s\n' % (self.name, self.on, START, END)),
             ('', 'source card "generated by engine/tests/properties/gen_m1.py"\n'),
             ('', 'unit DUK: currency minor 0.01\n'),
             ('', 'kind ext: place DUK signed outside\n'),
             ('', 'index month = month %s..%s\n' % (MONTHS[0], MONTHS[-1])),
             ('', 'index qs = [q1, q2, q3]\n')]
        s += [('', 'place %s: ext lives %s..\n' % (p, START)) for p in self.out]
        s += [('', 'place %s: accounts DUK lives %s..\n' % (p, START)) for p in self.acc]
        rows, ordered = [], []
        for m in self.moves + self.extra_moves:
            law = m.get('law')
            s.append(('', 'input amt_%s: money DUK question "How much does %s move?"\n' % (m['id'], m['id'])))
            s.append(('', 'input day_%s: date question "On what day does %s move?"\n' % (m['id'], m['id'])))
            at = 'law_%s' % m['id'] if law else 'day_%s' % m['id']
            if law:
                s.append(('', 'input law_%s: date\n' % m['id']))
                rows.append('law_%s = %s' % (m['id'], law))
            s.append(('', 'move %s: transfers\n  on day_%s\n  at %s\n  leg cash from %s to %s amount amt_%s\n'
                      % (m['id'], m['id'], at, m['src'], m['dst'], m['id'])))
            rows += ['amt_%s = %s' % (m['id'], m['amt']), 'day_%s = %s' % (m['id'], m['day'])]
        if self.plan:
            p = self.plan
            s.append(('', 'input plan_amt: money DUK question "How much does the plan move a month?"\n'))
            s.append(('', 'input plan_off: int\n'))
            s.append(('', 'move plan[m in month]: transfers\n  on add_days(start_of(m), plan_off)\n  at start_of(m)\n'
                          '  leg cash from %s to %s amount plan_amt\n' % (p['src'], p['dst'])))
            rows += ['plan_amt = %s' % p['amt'], 'plan_off = %d' % p['off']]
        if self.split:
            p = self.split
            s.append(('', 'input split_amt: money DUK question "How much is split?"\n'))
            s.append(('', 'input split_day: date\n'))
            s.append(('', 'input split_step: money DUK\n'))
            s.append(('', 'input w[k in qs]: num\n'))
            s.append(('', 'def share[k in qs]: money DUK = prorata(split_amt, w[j] for j in qs, k, split_step, rest '
                          'largest ties by pos(j))\n'))
            s.append(('', 'move split[k in qs]: transfers\n  on split_day\n  at split_day\n  leg cash from %s to %s '
                          'amount share[k]\n' % (p['src'], p['dst'])))
            rows += ['split_amt = %s' % p['amt'], 'split_day = %s' % p['day'], 'split_step = 0.01']
            rows += ['w[q%d] = %d' % (i + 1, w) for i, w in enumerate(p['w'])]
        if self.fee:
            p = self.fee
            s.append(('', 'input fee_base: money DUK question "What is the fee\'s base?"\n'))
            s.append(('', 'input fee_rate: num question "What is the fee\'s rate?"\n'))
            s.append(('', 'input fee_day: date\n'))
            s.append(('', 'band tier(x: num DUK): num\n'))
            s.append(('', 'def fee: money DUK\n  rule base = round(fee_base * fee_rate, minor(DUK), half-up)\n'
                          '  rule waived beats base = 0 DUK when fee_rate == 0\n'))
            s.append(('', 'def bonus: money DUK = round(fee_base * tier(fee_base), minor(DUK), half-up)\n'))
            s.append(('', 'move pay_fee: transfers\n  on fee_day\n  at fee_day\n  leg cash from %s to %s amount '
                          'fee + bonus\n' % (p['src'], p['dst'])))
            rows += ['fee_base = %s' % p['base'], 'fee_rate = %s' % p['rate'], 'fee_day = %s' % p['day']]
            ordered += ['tier: [0, 1000) = 0.01', 'tier: [1000, inf) = 0.02']  # a band's rows in order (LOAD-BAND)
        if self.sweep:
            w = self.sweep
            s.append(('', 'input sweep_floor: money DUK\n'))
            s.append(('', 'input sweep_day: date\n'))
            read = 'bal(%s)' % w['src']
            if w.get('reach'):  # the projection's lowest balance through its reach, `low` (L §5.14.1)
                s.append(('', 'input sweep_reach: date\n'))
                s.append(('', 'def low_room: money DUK = low(%s, sweep_day .. sweep_reach) from sweep_day at '
                              'sweep_day\n' % w['src']))
                rows.append('sweep_reach = %s' % w['reach'])
                read = 'low_room'
            s.append(('', 'move sweep: transfers\n  on sweep_day\n  at sweep_day\n  reads %s\n  leg cash from %s to %s '
                          'amount max(0, %s - sweep_floor)\n' % (w['src'], w['src'], w['dst'], read)))
            rows += ['sweep_floor = %s' % w['floor'], 'sweep_day = %s' % w['day']]
        if self.ksweep:
            w = self.ksweep
            s.append(('', 'input ks_floor: money DUK\n'))
            s.append(('', 'input ks_off: int\n'))
            s.append(('', 'move ksweep[m in month]: transfers\n  on add_days(start_of(m), ks_off)\n  at start_of(m)\n'
                          '  reads %s\n  leg cash from %s to %s amount max(0, bal(%s) - ks_floor)\n'
                          % (w['src'], w['src'], w['dst'], w['src'])))
            rows += ['ks_floor = %s' % w['floor'], 'ks_off = %d' % w['off']]
        if self.life:
            p, a, b, t1, t2, amt, src = self.life
            s.append(('', 'place %s: accounts DUK lives %s..%s\n' % (p, a, b)))
            s.append(('', 'input life_in: date\n'))
            s.append(('', 'input life_out: date\n'))
            s.append(('', 'input life_amt: money DUK\n'))
            s.append(('', 'move life_put: transfers\n  on life_in\n  at life_in\n  leg cash from %s to %s amount '
                          'life_amt\n' % (src, p)))
            s.append(('', 'move life_take: transfers\n  on life_out\n  at life_out\n  leg cash from %s to %s amount '
                          'life_amt\n' % (p, src)))
            rows += ['life_in = %s' % t1, 'life_out = %s' % t2, 'life_amt = %s' % amt]
        rows += ['opening[%s] = %s at %s start' % (a, v, START) for a, v in sorted(self.openings.items())]
        rows = [x for x in rows if not (self.drop and x.startswith(self.drop + ' = '))]
        self.layout.shuffle(rows)
        rows += ordered
        s.append(('', 'version facts\n  cite card\n  governs always\n  known %s\n' % START
                  + ''.join('  %s\n' % x for x in rows)))
        s += [('', 'ask %s: %s\n' % a) for a in self.asks]
        return s

    def scenario_file(self):
        d, rows = self.scenario
        return ('s.tally', 'scenario s over %s\n  tally 2\n  from %s\n\nversion sv\n  cite card\n  governs %s..\n'
                           '  known %s\n%s' % (self.name, d, d, START, ''.join('  replace %s\n' % x for x in rows)))

    def files(self, split=False):
        """One file (and the scenario's), or (split) the model's sections spread over 2-3 files in shuffled order."""
        self.layout = random.Random(self.name)
        secs = self.sections()
        extra = [self.scenario_file()] if self.scenario else []
        if not split:
            return [('reality.tally', '\n'.join(t for _, t in secs))] + extra
        r = self.layout
        n = r.randint(2, 3)
        head, rest = secs[0], secs[1:]
        r.shuffle(rest)
        bins = [[] for _ in range(n)]
        for x in rest:
            bins[r.randrange(n)].append(x)
        names = ['model.tally'] + ['part_%d.tally' % i for i in range(1, n)]
        out = []
        for i, b in enumerate(bins):
            body = ([head[1]] if i == 0 else ['part p%d\n  tally 2\n' % i]) + [t for _, t in b]
            out.append((names[i], '\n'.join(body)))
        out += extra
        r.shuffle(out)
        return out


def all_flows(x):
    return ', '.join('flows(%s, %s)' % (p, SPAN) for p in x.places())


def bals(x, d=END, world=''):
    return ', '.join('bal(%s, %s)' % (p, d) for p in x.acc) + world


def vals(x):
    v = []
    if x.split:
        v += ['share[q1]', 'share[q2]', 'share[q3]']
    if x.fee:
        v += ['fee', 'bonus']
    return ', '.join(v)


def rich(r, name, **kw):
    """A reality with every M1 form but lifespans and scenarios, the decisions at random."""
    return R1(r, name, sweep=r.random() < 0.5, ksweep=r.random() < 0.5, **kw)


