//! P8-M4, one point read of a written projection in E §4.3's common case: its wall time on the
//! reference Mac.
//! Spec: P §8.4 (P8-M4), §8.1 (P8-5), §2.3 (the common case); L §5.14.1; E §4.3.
//! Twin: none, an instrument (R-91); its instruction count is
//! `engine/tools/gungraun/benches/p8_m4.rs`, on the same reality.
//! Invariants: the setup is the builder's request at G7 (BUILD-LOG, 2026-11-01); the library
//! is reached only through `tally::run`, the reality given as bytes; after timing, each ask's
//! printed value is checked against the closed form opening + n × amount, so a fast wrong
//! answer fails the run.
//!
//! One place lives 33 years (12 054 days) with one plan movement a day. `P8-M4` times a whole
//! run asking `bal(x, E) from S`, `P8-M4-plain` the same reality asking `bal(x, E)`: a run is
//! read, parse, load and the walk, so the read itself is the difference of the two medians.

use criterion::{BatchSize, Criterion, criterion_group, criterion_main};
use std::hint::black_box;
use tally::{Answer, Asks, Days, Given, NotImplemented, Pin, Request, run};

/// The run's first day, S, and the projection's day t.
const START: &str = "2025-01-01";
/// The run's last day, E: S + 12 053 days.
const END: &str = "2058-01-01";
/// The days S..E, one plan movement each.
const DAYS: i64 = 12_054;
/// The daily amount, in minor units (1.25 DUK).
const AMOUNT: i64 = 125;
/// The place's opening balance, in minor units (100.00 DUK).
const OPENING: i64 = 10_000;

/// The reality, written in tally 2.1.1 as the corpus writes it, with the two asks.
fn reality() -> String {
    format!(
        "model p8m4\n  tally 2\n  on {START}\n  start {START}\n  end {END}\n\n\
         source card \"P8-M4's reality, generated by its bench\"\n\n\
         unit DUK: currency minor 0.01\n\n\
         kind ext: place DUK signed outside\n\n\
         place out: ext lives {START}..\n\n\
         place x: accounts DUK lives {START}..\n\n\
         input amt: money DUK\n\n\
         move pay[d in days]: transfers\n  on d\n  leg cash from out to x amount amt\n\n\
         version facts\n  cite card\n  governs always\n  known {START}\n  amt = 1.25\n  \
         opening[x] = 100.00 at {START} start\n\n\
         ask plain: bal(x, {END})\n\n\
         ask proj: bal(x, {END}) from {START}\n"
    )
}

/// The run's one file (built untimed).
fn given(text: &str) -> Vec<Given> {
    vec![Given {
        path: "p8m4.tally".to_owned(),
        bytes: Some(text.as_bytes().to_vec()),
    }]
}

/// A request for the one ask named.
fn request(ask: &str) -> Request {
    Request {
        asks: Asks::Named(vec![ask.to_owned()]),
        pin: Pin::Canonical,
        days: Days::Events,
    }
}

/// Minor units as the engine prints money: whole units grouped by threes with a space, two
/// decimals (`15 167.50`). None on overflow.
fn money_text(minor: i64) -> Option<String> {
    let whole = minor.checked_div_euclid(100)?;
    let cents = minor.checked_rem_euclid(100)?;
    let digits = whole.to_string();
    let mut grouped = String::new();
    for (i, digit) in digits.chars().enumerate() {
        let left = digits.len().checked_sub(i)?;
        if i > 0 && left.checked_rem_euclid(3)? == 0 {
            grouped.push(' ');
        }
        grouped.push(digit);
    }
    Some(format!("{grouped}.{cents:02}"))
}

/// The lines the ask must print: opening + n × amount, at the cut S.
fn known(ask: &str) -> Option<Vec<String>> {
    let balance = DAYS.checked_mul(AMOUNT)?.checked_add(OPENING)?;
    Some(vec![
        format!("{ask}: {} DUK", money_text(balance)?),
        format!("  cut {START}"),
    ])
}

/// Whether the answer printed is the known one.
fn right(answer: &Result<Answer, NotImplemented>, ask: &str) -> bool {
    match (answer, known(ask)) {
        (Ok(answer), Some(lines)) => answer.lines() == lines.as_slice(),
        _ => false,
    }
}

/// Times whole runs of one ask, then says whether one run prints the known value.
fn timed(bench: &mut Criterion, id: &str, ask: &str) -> bool {
    let text = reality();
    let asked = request(ask);
    bench.bench_function(id, |t| {
        t.iter_batched(
            || given(&text),
            |files| run(black_box(files), black_box(&asked)),
            BatchSize::SmallInput,
        );
    });
    right(&run(given(&text), &asked), ask)
}

fn p8_m4(bench: &mut Criterion) {
    assert!(
        timed(bench, "P8-M4", "proj"),
        "P8-M4: a fast wrong answer fails"
    );
    assert!(
        timed(bench, "P8-M4-plain", "plain"),
        "P8-M4-plain: a fast wrong answer fails"
    );
}

criterion_group! {
    name = benches;
    // a run takes about 0.3 s, so ten samples, criterion's least
    config = Criterion::default().sample_size(10);
    targets = p8_m4
}
criterion_main!(benches);
